function card([title, value]) {
  const rows = Array.isArray(value)
    ? `<dl>${value.map(([name, text]) => `<div><dt>${esc(name)}</dt><dd>${esc(text)}</dd></div>`).join('')}</dl>`
    : `<p>${esc(value)}</p>`;
  return `<li><h3>${esc(title)}</h3>${rows}</li>`;
}

function block(b) {
  if (typeof b === 'string') return `<p>${esc(b)}</p>`;
  if (Array.isArray(b)) return `<ul>${b.map((i) => `<li>${esc(i)}</li>`).join('')}</ul>`;
  return `<ul class="doc-cards">${b.cards.map(card).join('')}</ul>`;
}

